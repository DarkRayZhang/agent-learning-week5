TOPIC_NAMES = list(ENTRIES.keys())


def build_doc(idx: int, rng: random.Random) -> str:
    """生成第 idx 篇文档：主主题 3~4 小节 + 次主题 2 小节。"""
    main_topic = rng.choice(TOPIC_NAMES)
    other_topics = [t for t in TOPIC_NAMES if t != main_topic]
    sub_topic = rng.choice(other_topics)

    main_entries = rng.sample(ENTRIES[main_topic], rng.randint(3, 4))
    sub_entries = rng.sample(ENTRIES[sub_topic], 2)

    lines = [
        f"# 备忘 {idx:03d}",
        "",
        f"> 主题：{main_topic} ｜ 记于 2026-09-15",
        "",
    ]
    for title, sentences in main_entries + sub_entries:
        lines.append(f"## {title}")
        lines.append("。".join(sentences) + "。")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    out_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "docs")
    os.makedirs(out_dir, exist_ok=True)

    rng = random.Random(SEED)
    total_chars = 0
    for i in range(1, 101):
        content = build_doc(i, rng)
        total_chars += len(content)
        with open(os.path.join(out_dir, f"doc_{i:03d}.md"), "w", encoding="utf-8") as f:
            f.write(content)

    print(f"已生成 100 篇文档到 docs/")
    print(f"总字符数 {total_chars}，平均每篇 {total_chars // 100} 字符")
    print(f"→ 按 chunk 500 / overlap 50 切，预计每篇 2~3 块")


if __name__ == "__main__":
    main()
